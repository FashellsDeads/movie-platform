const reviewDate = (index) => `2026-11-${String(18 - (index % 15)).padStart(2, '0')}`

const toMovie = ({ poster, showtimes, reviews, ...movie }) => ({
  ...movie,
  type: 'movie',
  imageUrl: createPoster(...poster),
  showtimes: showtimes.map(([time, hall]) => ({ time, hall: HALLS[hall] })),
  reviews: reviews.map(([author, rating, text], index) => ({
    id: `${movie.id}-${index + 1}`,
    author,
    rating,
    text,
    date: reviewDate(movie.id + index),
  })),
})

const toBarItem = ([id, title, category, price, rating, description]) => ({
  id,
  type: 'bar',
  title,
  category,
  price,
  rating,
  description,
  imageUrl: createPoster(title[0], BAR_COLORS[category]),
  reviews: [],
})

